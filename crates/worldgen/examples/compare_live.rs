//! Compares the Wang biome maps of a running game with the ported generator:
//! `noita_probe biomes <dir>` in the game, then `cargo run --release -p worldgen --example
//! compare_live -- <dir>`.

use std::path::PathBuf;

use worldgen::generate::{convert_biome, load_biomes, load_materials, wang_offset};

fn main() {
    let dir = PathBuf::from(std::env::args().nth(1).expect("dump directory"));
    let files = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../noita_files");
    let world = std::fs::read_to_string(dir.join("world.txt")).expect("world.txt");
    let mut lines = world.lines();
    let seed: i32 = lines
        .next()
        .and_then(|l| l.strip_prefix("seed "))
        .and_then(|s| s.parse().ok())
        .expect("seed");
    let offset_bits: Vec<u64> = lines
        .next()
        .and_then(|l| l.strip_prefix("offset "))
        .expect("offset")
        .split(' ')
        .map(|s| u64::from_str_radix(s.trim_start_matches("0x"), 16).unwrap())
        .collect();
    let live_offset = (
        f64::from_bits(offset_bits[0]),
        f64::from_bits(offset_bits[1]),
    );
    let ours = wang_offset(seed as u32);
    println!(
        "world seed {seed}\nlive wang offset {live_offset:?}\nported          {ours:?}  {}",
        if ours == live_offset {
            "MATCH"
        } else {
            "DIFFERENT"
        }
    );

    let defs = load_materials(&files).expect("materials");
    let loaded = load_biomes(&files, &defs, seed as u32, None).expect("load biomes");
    let ported: Vec<_> = loaded
        .iter()
        .enumerate()
        .filter_map(|(i, b)| Some((i, b.file.clone(), convert_biome(&files, &defs, b)?)))
        .collect();
    println!("{} Wang maps generated by the port", ported.len());

    let mut entries: Vec<_> = std::fs::read_dir(&dir)
        .unwrap()
        .flatten()
        .filter(|e| {
            e.file_name().to_string_lossy().ends_with(".txt") && e.file_name() != "world.txt"
        })
        .collect();
    entries.sort_by_key(|e| {
        e.file_name()
            .to_string_lossy()
            .trim_end_matches(".txt")
            .parse::<u32>()
            .unwrap_or(0)
    });
    for e in entries {
        let text = std::fs::read_to_string(e.path()).unwrap();
        let mut l = text.lines();
        let head: Vec<&str> = l.next().unwrap().split(' ').collect();
        let (file, w, h) = (
            head[0],
            head[2].parse::<i32>().unwrap(),
            head[3].parse::<i32>().unwrap(),
        );
        let values: Vec<u32> = l
            .next()
            .unwrap()
            .split(' ')
            .map(|s| u32::from_str_radix(s, 16).unwrap())
            .collect();
        let mats: Vec<u16> = l
            .next()
            .unwrap()
            .split(' ')
            .map(|s| s.parse().unwrap())
            .collect();
        let candidates: Vec<_> = ported.iter().filter(|(_, f, _)| f == file).collect();
        let mut report = Vec::new();
        for (idx, _, c) in &candidates {
            let same_size = (c.map.values.width, c.map.values.height) == (w, h);
            let float_diff = if same_size {
                c.map
                    .values
                    .data
                    .iter()
                    .zip(&values)
                    .filter(|(a, b)| a.to_bits() != **b)
                    .count()
            } else {
                usize::MAX
            };
            let mat_diff = if same_size {
                c.map
                    .materials
                    .data
                    .iter()
                    .zip(&mats)
                    .filter(|(a, b)| a != b)
                    .count()
            } else {
                usize::MAX
            };
            report.push(format!(
                "entry {idx}: {float_diff} float / {mat_diff} material pixels differ"
            ));
        }
        println!(
            "{} ({w}x{h}): {}",
            file,
            if report.is_empty() {
                "no ported map".to_owned()
            } else {
                report.join("; ")
            }
        );
    }
}
